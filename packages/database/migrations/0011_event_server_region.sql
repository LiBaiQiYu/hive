-- =============================================================================
-- HIVE V1.0 · 011 赛事服务器（国服 / 全球服）
-- -----------------------------------------------------------------------------
-- 同一场内战只能在一个服务器打：国服（完美世界）与全球服是两个独立的匹配池，
-- 房间也互相连不上。进错服 = 和队友碰不上，所以这一项要写在赛事上、并且公开展示。
--
--   GLOBAL —— 全球服：Steam 直接启动 Dota2，不加任何启动项
--   CN     —— 国服：蒸汽平台启动，或 Steam 的 Dota2 启动项加 -perfectworld
--
-- 默认 GLOBAL：什么都不做就是 Steam 国际服的行为。历史赛事一并按 GLOBAL 处理，
-- 管理员可以在编辑页改成国服。
-- =============================================================================

ALTER TABLE events ADD COLUMN server_region TEXT NOT NULL DEFAULT 'GLOBAL'
  CHECK (server_region IN ('CN', 'GLOBAL'));
