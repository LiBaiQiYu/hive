-- 0015 · 邮箱可用性确认
--
-- 为什么要这一列：密码只能靠注册邮箱找回（发一封空白邮件到 reset@ 后回信带链接）。
-- 但很多账号是随手填的邮箱、或者填完就再也没打开过，等到真忘了密码才发现收不到信。
-- 现在玩家可以在「账号设置」点一次「我确认这个邮箱能收到信」，把时间戳记下来；
-- 没确认的人每次登录都会在页面顶部看到一条提醒。
--
-- 换邮箱时把这个值清空（见 PATCH /api/me）：新地址要重新确认。
-- 它只是提示用的状态，不参与鉴权，也不影响登录。
ALTER TABLE users ADD COLUMN email_confirmed_at INTEGER;
